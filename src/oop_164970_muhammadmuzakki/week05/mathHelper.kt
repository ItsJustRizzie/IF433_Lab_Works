package oop_164970_muhammadmuzakki.week05

class MathHelper {
    fun areaCalculator(side: Int): Int {
        return side * side
    }

    fun areaCalculator(length: Int, width: Int): Int {
        return length * width
    }

    fun areaCalculator(radius: Double): Double {
        return 3.14 * radius * radius
    }
}